# base.py
#
# This file defines the `Base` class, which serves as the foundation for all ORM models.
# The `Base` class provides essential methods for interacting with the database, such as:
#   - `save()`: Insert or update the current model instance in the database.
#   - `_insert()`: Insert the current instance into the database (private method).
#   - `_update()`: Update the current instance in the database (private method).
#   - `get()`: Retrieve a record by its ID.
#   - `delete()`: Delete a record by its ID.
#   - `all()`: Retrieve all records of the model from the database.
#   - `query()`: Query records based on filter conditions.
#   - `create_schema()`: Generate the schema (sql code) for the model in the database.
#   - `create()`: Uses the generated schema from the previous function to create a table in the database based on the model's schema.
#   - `join()`: Join multiple models together for data retrieval.
#   - `where()`: Add WHERE conditions to queries.
#   - `having()`: Add HAVING conditions to queries.
#   - `group_by()`: Add GROUP BY clauses to queries.
#
# Connection management is critical. Every method interacting with the database must:
#   - Open a new connection and cursor at the start of the operation.
#   - Close the cursor and connection after the operation is complete,
#     whether the operation is successful or not, to avoid memory leaks.
#   - Transactions must be committed on success, and rolled back on failure.
#
# Students should implement proper connection management in each method, including:
#   - Using `try`, `except`, and `finally` to ensure the connection and cursor are always closed.
#   - Handling potential exceptions during database operations and performing rollbacks if needed.
#
# The `Base` class is meant to be subclassed, and any model that extends `Base` will automatically
# inherit the methods for database interaction.


from api.db_connectors import MySQL
from api.columns import Column


class Base:
    _registry = {}      # model name -> model class
    _identity_map = {}  # (table_name, pk_value) -> instance

    def __init_subclass__(cls, **kwargs):
        super().__init_subclass__(**kwargs)
        Base._registry[cls.table_descriptor()] = cls

    def __init__(self, **kwargs):
        """Initialize model instance with attributes."""
        for key, value in kwargs.items():
            setattr(self, key, value)


    def save(self):
        """Insert or update the record in the database.
        """
        pk = self.primary_key()

        if pk in self.__dict__ and self.__dict__[pk] is not None:
            # print("I am updating...")
            self._update()
        else:
            # print("I am inserting")
            self._insert()


    def _insert(self):
        """Insert the current instance into the database.
        """
        # INSERT INTO table (attributes separated by comma) VALUES
        #                      (placeholders separated by comma)
        table = self.table_descriptor()
        columns = self.columns()
        attributes = [attr for attr, column in columns.items() if not column.is_primary_key()]
        fields = ", ".join(attributes)
        values = [self.__dict__.get(attr) for attr in attributes]
        placeholders = ", ".join(["%s"] * len(attributes))

        # INSERT INTO User (username, email) VALUES (%s, %s)
        # INSERT INTO Incident_Report (description, user_id) VALUES (%s, %s)
        query = f"INSERT INTO {table} ({fields}) VALUES ({placeholders})"

        connection, cursor = MySQL.instance()

        try:
            cursor.execute(query, values)
            connection.commit()
            pk_value = cursor.lastrowid
            if pk_value:
                pk = self.primary_key()
                setattr(self, pk, pk_value)  # new id generated by the insert and assigning it to that pk
                Base.add_identity_instance(self)

        except Exception as e:
            # handle errors and any rollbacks
            connection.rollback()
            raise e

        finally:
            # close components to avoid memory leaks
            connection.close()
            cursor.close()


    def _update(self):
        """Update the current instance in the database.
        """
        # UPDATE table SET attr1=placeholder1, attr2=placeholder2, ...
        #                    attrn=placeholdern WHERE pk = placeholder
        table = self.table_descriptor()
        columns = self.columns()
        attributes = [attr for attr, column in columns.items() if not column.is_primary_key()]
        values = [self.__dict__[attr] for attr in attributes]
        pk = self.primary_key()
        pk_value = getattr(self, pk, None)
        values.append(pk_value)
        fields = [f"{attr}=%s" for attr in attributes]
        fields_separated_by_comma = ", ".join(fields)

        query = f"UPDATE {table} SET {fields_separated_by_comma} WHERE {pk} = %s"
        # print(query)
        connection, cursor = MySQL.instance()

        try:
            cursor.execute(query, values)
            connection.commit()
        except Exception as e:
            # handle errors and any rollbacks
            connection.rollback()
            raise e

        finally:
            # close components to avoid memory leaks
            connection.close()
            cursor.close()


    @classmethod
    def get(cls, id):
        """Retrieve a record from the database by its ID.
        """
        # SELECT * FROM table WHERE pk = %s
        key = cls.identity_key(id)
        if key in cls._identity_map:
            return cls._identity_map[key]

        table = cls.table_descriptor()
        pk = cls.primary_key()

        query = f"SELECT * FROM {table} WHERE {pk} = %s"

        connection, cursor = MySQL.instance()

        try:
            cursor.execute(query, (id,))
            result = cursor.fetchone()
            if result is None:
                return None
            obj = cls(**result)
            cls.add_identity_instance(obj)
            return obj

        except Exception as e:
            # handle errors and any rollbacks
            raise e

        finally:
            # close components to avoid memory leaks
            connection.close()
            cursor.close()


    @classmethod
    def delete(cls, id):
        """Delete a record from the database by its ID.
        """
        table = cls.table_descriptor()
        pk = cls.primary_key()
        query = f"DELETE FROM {table} WHERE {pk} = %s"

        connection, cursor = MySQL.instance()

        try:
            cursor.execute(query, (id,))
            connection.commit()
            key = cls.identity_key(id)
            if key in cls._identity_map:
                del cls._identity_map[key]
        except Exception as e:
            connection.rollback()
            raise e

        finally:
            connection.close()
            cursor.close()


    @classmethod
    def all(cls):
        """Retrieve all records of this model from the database.
        """
        # SELECT * FROM table
        table = cls.table_descriptor()

        query = f"SELECT * FROM {table}"

        connection, cursor = MySQL.instance()

        try:
            cursor.execute(query)
            results = cursor.fetchall()
            all_results = []
            for result in results:
                obj = cls(**result)
                cls.add_identity_instance(obj)
                all_results.append(obj)
            return all_results

        except Exception as e:
            # handle errors and any rollbacks
            raise e

        finally:
            # close components to avoid memory leaks
            connection.close()
            cursor.close()


    @classmethod
    def query(cls, **filters):
        """Query records based on filter conditions.
        Example:
            delayed_reports = Incident_Report.query(status='Delayed', priority_id=3)
            user_reports = Incident_Report.query(user_id=42)
        """
        table = cls.table_descriptor()

        # If no filters provided, return all records
        if not filters:
            return cls.all()

        # Build WHERE conditions
        conditions = []
        values = []

        for column, value in filters.items():
            conditions.append(f"{column} = %s")
            values.append(value)

        where_clause = " WHERE " + " AND ".join(conditions)

        query = f"SELECT * FROM {table}{where_clause}"

        connection, cursor = MySQL.instance()
        try:
            cursor.execute(query, values)
            results = cursor.fetchall()

            # Convert each row into a model instance
            instances = []
            for row in results:
                obj = cls(**row)
                cls.add_identity_instance(obj)
                instances.append(obj)
            return instances

        except Exception as e:
            raise e
        finally:
            connection.close()
            cursor.close()


    @classmethod
    def create(cls, **attributes):
        """Insert a new record in an existing schema without exposing the class constructor.

        This is a convenience method to create and save an object in one step.

        Args:
            **attributes: Column names and their values (keyword arguments)

        Returns:
            The newly created model instance (with primary key populated)

        Example:
            new_report = Incident_Report.create(
                description="Train delayed 20 minutes",
                category_id=3,
                user_id=42,
                priority_id=2
            )
            print(new_report.incident_id)   # ID is now available
        """
        # Create instance from attributes
        instance = cls(**attributes)

        # Save to database (this also sets the auto-generated primary key)
        instance._insert()

        return instance


    @classmethod
    def create_schema(cls):
        """Generate the schema for the model in the database.
        """
        table = cls.table_descriptor()
        columns = cls.columns()
        col_defs = []
        pk_columns = []
        for name, col in columns.items():
            # Ensure the column's type is an instance (not a class)
            col.validate_type()
            col_sql = f"{name} {col.type.to_sql()}"
            constraints = []
            if not col.nullable:
                constraints.append("NOT NULL")
            if col.unique:
                constraints.append("UNIQUE")
            if col.auto_increment:
                constraints.append("AUTO_INCREMENT")
            if col.default is not None:
                if isinstance(col.default, str):
                    constraints.append(f"DEFAULT '{col.default}'")
                else:
                    constraints.append(f"DEFAULT {col.default}")
            if col.foreign_key:
                fk = f"REFERENCES {col.foreign_key}"
                if col.on_update:
                    fk += f" ON UPDATE {col.on_update}"
                if col.on_delete:
                    fk += f" ON DELETE {col.on_delete}"
                constraints.append(fk)
            if col.primary_key:
                pk_columns.append(name)   # collect for table-level PK
            # Do NOT add PRIMARY KEY here (will add as separate constraint)
            if constraints:
                col_sql += " " + " ".join(constraints)
            col_defs.append(col_sql)
        # Add table-level primary key if any columns are primary keys
        if pk_columns:
            col_defs.append(f"PRIMARY KEY ({', '.join(pk_columns)})")
        create_sql = f"CREATE TABLE IF NOT EXISTS {table} (\n  " + ",\n  ".join(col_defs) + "\n)"
        connection, cursor = MySQL.instance()
        try:
            cursor.execute(create_sql)
            connection.commit()
        except Exception as e:
            connection.rollback()
            raise e
        finally:
            connection.close()
            cursor.close()


    @classmethod
    def join(cls, models):
        """Join multiple models to organize your data.

        Args:
            models (list): List of model classes to join with the main model.

        Example:
            results = Incident_Report.join([User, Station])

        Returns:
            List of dictionaries containing joined data.
        """
        if not models or not isinstance(models, list):
            return cls.all()

        main_table = cls.table_descriptor()
        select_parts = [f"{main_table}.*"]
        join_clauses = []

        for model in models:
            join_table = model.table_descriptor()

            # Add all columns from joined table with table prefix to avoid ambiguity
            select_parts.append(f"{join_table}.*")

            # === Simple Join Logic (Common Convention) ===
            # Try to guess the foreign key:
            #   e.g. Incident_Report.user_id  -> User.user_id
            #   or  Incident_Report.station_id -> Station.station_id
            fk_column = f"{join_table.lower()}_id"

            if fk_column in cls.columns():  # Check if main model has the FK
                on_condition = f"{main_table}.{fk_column} = {join_table}.{join_table.lower()}_id"
            else:
                # Fallback: assume reverse (less common)
                on_condition = f"{main_table}.{main_table.lower()}_id = {join_table}.{main_table.lower()}_id"

            join_clauses.append(f"LEFT JOIN {join_table} ON {on_condition}")

        # Build final query
        query = f"""
            SELECT {', '.join(select_parts)}
            FROM {main_table}
            {' '.join(join_clauses)}
        """

        connection, cursor = MySQL.instance()
        try:
            cursor.execute(query)
            rows = cursor.fetchall()

            # Convert to list of dictionaries for easier use
            columns = [desc[0] for desc in cursor.description]
            results = [dict(zip(columns, row)) for row in rows]

            return results

        except Exception as e:
            raise e
        finally:
            connection.close()
            cursor.close()


    @classmethod
    def where(cls, **conditions):
        """Add WHERE conditions to a query.
        """
        if not conditions:
            return ""

        parts = []
        for column, value in conditions.items():
            parts.append(f"{column} = %s")

        return "WHERE " + " AND ".join(parts)


    @classmethod
    def having(cls, **conditions):
        """Add HAVING conditions to a query.
        Example:
            # For a query like: ... GROUP BY category_id HAVING COUNT(*) > 5
            having_str, values = Incident_Report.having(count__gt=5)
            # Or simple equality:
            having_str, values = Incident_Report.having(priority_id=3)
        """
        if not conditions:
            return "", []

        parts = []
        values = []

        for key, value in conditions.items():
            # Basic support for simple equality
            # You can extend this later for >, <, >=, etc.
            parts.append(f"{key} = %s")
            values.append(value)

        having_clause = " AND ".join(parts)

        return having_clause, values


    @classmethod
    def group_by(cls, *columns):
        """Add GROUP BY clauses to a query.
        """
        if not columns:
            return ""
        return "GROUP BY " + ", ".join(columns)


    @classmethod
    def table_descriptor(cls):
        """
        :return: the name of the table t
        """
        return cls.__name__


    @classmethod
    def columns(cls):
        """
        :return: the list of column names
        """
        return {name: column for name, column in cls.__dict__.items() if isinstance(column, Column)}


    @classmethod
    def primary_key(cls):
        """
        :return: the primary key attribute name, not the value.
                 for example student_id = 1, will return student_id, not the value 1
        """
        columns = cls.columns()
        for name, column in columns.items():
            if column.is_primary_key():
                return name
        return 'id'


    @classmethod
    def resolve_model(cls, model_name):
        return cls._registry.get(model_name)


    @classmethod
    def identity_key(cls, pk_value):
        return (cls.table_descriptor(), pk_value)


    @classmethod
    def get_identity_instance(cls, pk_value):
        key = cls.identity_key(pk_value)
        return cls._identity_map.get(key)


    @classmethod
    def add_identity_instance(cls, obj):
        pk = cls.primary_key()
        pk_value = getattr(obj, pk, None)
        if pk_value is None:
            return obj
        key = cls.identity_key(pk_value)
        cls._identity_map[key] = obj
        return obj
